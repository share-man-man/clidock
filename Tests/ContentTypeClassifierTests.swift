import AppKit
import SwiftData
import XCTest

@MainActor
final class ContentTypeClassifierTests: XCTestCase {
    /// Private settings domain for this test's capture preferences.
    private let suiteName = "PopbackTests.Privacy.\(UUID().uuidString)"
    private var defaults: UserDefaults!
    private var pasteboard: NSPasteboard!
    /// The monitor uses one classifier even when the user changes a preference.
    private let classifier = ContentTypeClassifier()

    override func setUp() async throws {
        defaults = try XCTUnwrap(UserDefaults(suiteName: suiteName))
        pasteboard = .withUniqueName()
    }

    override func tearDown() async throws {
        defaults.removePersistentDomain(forName: suiteName)
        pasteboard.releaseGlobally()
    }

    /// Classifies plain text from a private clipboard with the specified markers.
    /// - Parameter markers: Content-type markers supplied by the copying application.
    private func captures(_ markers: NSPasteboard.PasteboardType...) -> Bool {
        // Publish the marker types alongside the text, as a third-party application would.
        let item = NSPasteboardItem()
        item.setString("example", forType: .string)
        for marker in markers {
            item.setData(Data(), forType: marker)
        }
        pasteboard.clearContents()
        XCTAssertTrue(pasteboard.writeObjects([item]))
        return classifier.classify(pasteboard, defaults: defaults)?.textContent == "example"
    }

    func testDefaultIgnoresConfidentialAndTemporaryContent() {
        XCTAssertTrue(captures())
        XCTAssertFalse(captures(.concealedContent))
        XCTAssertFalse(captures(.transientContent))
        XCTAssertFalse(captures(.autoGeneratedContent))
    }

    func testPrivacyTogglesTakeEffectIndependentlyOnTheNextCopy() {
        defaults.set(false, forKey: ContentTypeClassifier.ignoresConfidentialDefaultsKey)
        XCTAssertTrue(captures(.concealedContent))
        XCTAssertFalse(captures(.concealedContent, .transientContent))
        XCTAssertFalse(captures(.autoGeneratedContent))

        defaults.set(false, forKey: ContentTypeClassifier.ignoresTransientDefaultsKey)
        XCTAssertTrue(captures(.concealedContent, .transientContent, .autoGeneratedContent))

        defaults.set(true, forKey: ContentTypeClassifier.ignoresConfidentialDefaultsKey)
        XCTAssertFalse(captures(.concealedContent, .transientContent))
        XCTAssertTrue(captures(.transientContent))
        XCTAssertTrue(captures(.autoGeneratedContent))
    }

    /// Finder, the history write and the consumer all use real items on a private pasteboard.
    func testFinderGroupSurvivesAnInterveningCopyAndRestoresInOrder() throws {
        /// Include duplicate basenames and characters that cannot be used as storage delimiters.
        let urls = ["/tmp/one/a.txt", "/tmp/two/a.txt", "/tmp/空 格#%\n.txt"].map { URL(fileURLWithPath: $0) }
        XCTAssertTrue(pasteboard.writeObjects(urls as [NSURL]))
        /// A history card stores every file in this single capture.
        let captured = try XCTUnwrap(classifier.classify(pasteboard, defaults: defaults))
        XCTAssertEqual(captured.contentType, .fileURL)
        XCTAssertEqual(captured.textContent, urls.map(\.lastPathComponent).joined(separator: "\n"))
        /// Simulate a later unrelated copy before restoring the saved card.
        let item = ClipboardItem(contentType: captured.contentType, rawData: captured.rawData,
                                 textContent: captured.textContent, contentHash: "test")
        pasteboard.clearContents()
        pasteboard.setString("intervening copy", forType: .string)
        PasteService().write(item: item, asPlainText: false, to: pasteboard)
        XCTAssertEqual(pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], urls)
        XCTAssertTrue(OwnPasteboardWrite.isOwn(pasteboard))
        XCTAssertEqual(classifier.classify(pasteboard, defaults: defaults)?.rawData, captured.rawData)
    }

    func testLegacySingleFileUsesTheSameFormatAndCanStillBePasted() throws {
        /// This is exactly the URL string stored by earlier releases.
        let url = URL(fileURLWithPath: "/tmp/old name.pdf")
        /// No optional text or thumbnails are needed to restore the original file reference.
        let item = ClipboardItem(contentType: .fileURL, rawData: Data(url.absoluteString.utf8), contentHash: "legacy")
        PasteService().write(item: item, asPlainText: true, to: pasteboard)
        XCTAssertEqual(pasteboard.string(forType: .fileURL), url.absoluteString)
        XCTAssertEqual(classifier.classify(pasteboard, defaults: defaults)?.rawData, item.rawData)
    }

    func testAFileSelectionTakesPrecedenceOverItsThumbnailButHonorsPrivacy() throws {
        /// Finder can offer a thumbnail alongside the first file reference.
        let first = NSPasteboardItem()
        first.setString("file:///tmp/image.png", forType: .fileURL)
        first.setData(Data([1]), forType: .png)
        /// The second file must stay attached to the first.
        let second = NSPasteboardItem()
        second.setString("file:///tmp/document.pdf", forType: .fileURL)
        XCTAssertTrue(pasteboard.writeObjects([first, second]))
        /// The preview image cannot replace the actual file selection.
        let captured = try XCTUnwrap(classifier.classify(pasteboard, defaults: defaults))
        XCTAssertEqual(captured.contentType, .fileURL)
        XCTAssertEqual(captured.textContent, "image.png\ndocument.pdf")
        pasteboard.setData(Data(), forType: .concealedContent)
        XCTAssertNil(classifier.classify(pasteboard, defaults: defaults))
    }

    func testFinderImageFileGetsAThumbnailAndPastesItsOriginalURL() async throws {
        /// Real image file large enough to require downsampling.
        let url = FileManager.default.temporaryDirectory.appendingPathComponent("\(UUID()).png")
        defer { try? FileManager.default.removeItem(at: url) }
        /// The two-to-one aspect ratio should survive the resize.
        let bitmap = try XCTUnwrap(NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 1024, pixelsHigh: 512,
                                                    bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true,
                                                    isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0))
        /// Finder may advertise both the file URL and a bitmap in a single pasteboard item.
        let png = try XCTUnwrap(bitmap.representation(using: .png, properties: [:]))
        try png.write(to: url)
        let file = NSPasteboardItem()
        file.setString(url.absoluteString, forType: .fileURL)
        file.setData(png, forType: .png)
        XCTAssertTrue(pasteboard.writeObjects([file]))
        XCTAssertEqual(classifier.classify(pasteboard, defaults: defaults)?.contentType, .image)
        /// Finder keeps the original file even when a pixel representation is present.
        let captured = try XCTUnwrap(classifier.classify(pasteboard, defaults: defaults, sourceBundleID: FileClip.finderBundleID))
        XCTAssertEqual(captured.contentType, .fileURL)
        XCTAssertEqual(captured.thumbnailFileURL, url)
        /// The card and paste service use the same persisted model.
        let store = try ModelContainer(for: ClipboardItem.self, configurations: ModelConfiguration(isStoredInMemoryOnly: true))
        let clip = ClipboardItem(contentType: captured.contentType, rawData: captured.rawData, textContent: captured.textContent, contentHash: "finder")
        store.mainContext.insert(clip)
        try store.mainContext.save()
        await FileImageThumbnail.storeIfNeeded(for: clip, from: url)
        /// A fresh context sees the preview saved by the decoder.
        let saved = try XCTUnwrap(ModelContext(store).fetch(FetchDescriptor<ClipboardItem>()).first?.thumbnailData)
        let preview = try XCTUnwrap(NSBitmapImageRep(data: saved))
        XCTAssertEqual(preview.pixelsWide, FileImageThumbnail.maxPixelSize)
        XCTAssertEqual(preview.pixelsHigh, preview.pixelsWide / 2)
        PasteService().write(item: clip, asPlainText: false, to: pasteboard)
        XCTAssertEqual(pasteboard.string(forType: .fileURL), url.absoluteString)
        XCTAssertNil(pasteboard.data(forType: .png))
        XCTAssertEqual(clip.contentType, .fileURL)
    }

    func testUnreadableImageFileKeepsItsFileRepresentation() async throws {
        /// Simulate a previous release's clip for a file removed before the card was opened.
        let url = FileManager.default.temporaryDirectory.appendingPathComponent("\(UUID()).png")
        let store = try ModelContainer(for: ClipboardItem.self, configurations: ModelConfiguration(isStoredInMemoryOnly: true))
        let clip = ClipboardItem(contentType: .fileURL, rawData: Data(url.absoluteString.utf8), contentHash: "missing")
        store.mainContext.insert(clip)
        try store.mainContext.save()
        await FileImageThumbnail.storeIfNeeded(for: clip, from: url)
        XCTAssertNil(clip.thumbnailData)
        // An image extension on corrupt or nonimage data also uses the file icon.
        try Data("invalid image".utf8).write(to: url)
        defer { try? FileManager.default.removeItem(at: url) }
        await FileImageThumbnail.storeIfNeeded(for: clip, from: url)
        XCTAssertNil(clip.thumbnailData)
        XCTAssertEqual(clip.rawData, Data(url.absoluteString.utf8))
    }
}
